// Простой бот по FAQ для чата на сайте: пытается ответить на типовые вопросы
// автоматически (используя company.faq), не дожидаясь администратора. Если
// уверенного совпадения нет — ничего не делает, диалог идёт как раньше
// (уходит человеку). Никакого внешнего AI API — быстрое совпадение по
// ключевым словам, поэтому предсказуемо и бесплатно.
//
// Первая версия сравнивала целые фразы ("сколько ждать", "как оплатить") —
// на практике люди пишут вопрос своими словами ("когда привезете", "можно
// картой?"), и с русским словоизменением (оплатить/оплата/оплатите/оплачу)
// точное совпадение фразы почти никогда не срабатывало — бот "не реагировал
// почти ни на что". Теперь совпадение ищется на уровне КОРНЯ слова: если
// хоть одно слово в вопросе НАЧИНАЕТСЯ с корня из списка — это засчитывается,
// что закрывает основные падежи/формы одним корнем без словаря морфологии.
import { company } from './company';

type FaqTopic = {
  answer: string;
  // Слово в вопросе засчитывается, если начинается с одного из этих корней
  // (значит ловит склонения/спряжения: "оплат" -> оплата, оплатить, оплаты, оплачу).
  roots: string[];
  // Более длинные характерные словосочетания — тоже как есть, для случаев,
  // где отдельного слова недостаточно (одно слово слишком общее).
  phrases?: string[];
};

