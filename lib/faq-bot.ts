function normalize(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9\s]/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Пытается найти ответ на вопрос посетителя среди типовых FAQ. Возвращает
 * текст ответа при совпадении (хотя бы один корень/фраза нашлись), иначе
 * null — тогда вопрос уходит человеку как обычно.
 */
export function matchFaq(message: string): string | null {
  const normalized = normalize(message);
  if (normalized.length < 2) return null;

  const words = normalized.split(' ');

  let best: { answer: string; score: number } | null = null;

  for (const topic of TOPICS) {
    let score = 0;
    for (const root of topic.roots) {
      if (words.some((w) => w.startsWith(root))) score++;
    }
    for (const phrase of topic.phrases ?? []) {
      if (normalized.includes(normalize(phrase))) score++;
    }
    if (score > 0 && (!best || score > best.score)) {
      best = { answer: topic.answer, score };
    }
  }

  return best?.answer ?? null;
}

