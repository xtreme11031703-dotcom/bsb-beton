export type ChatThreadIdentity = {
  visitorName: string | null;
  visitorSeq: number;
  client?: { name: string } | null;
};

/**
 * Единое правило "как называть посетителя чата" — используется и в админке,
 * и в Telegram-уведомлениях, чтобы не разъезжались в двух местах.
 *
 * Приоритет: если тред привязан к аккаунту клиента — берём его актуальное
 * имя из связи (а не снимок на момент создания треда, чтобы имя подтягивалось,
 * даже если человек сначала писал анонимно, а потом вошёл в аккаунт).
 * Иначе — стабильный порядковый номер "Клиент N" по visitorSeq. Мы больше не
 * подставляем сюда session.name при создании треда, потому что раньше это
 * писалось для ЛЮБОЙ вошедшей роли (в том числе для завода), из-за чего
 * анонимный посетитель мог отображаться как «завод», если виджет чата был
 * открыт залогиненным сотрудником завода.
 */
export function chatDisplayName(thread: ChatThreadIdentity): string {
  return thread.client?.name || thread.visitorName || `Клиент ${thread.visitorSeq}`;
}
